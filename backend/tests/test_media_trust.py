"""The learned press list: generated once, validated, stored, reused.

Hardcoding a press list per country does not scale — there are ~200
jurisdictions and nobody here can vouch for the business desk of a newspaper in a
market they have never read. So the list is generated by the model, validated
against a fixed rule set, and stored. These tests cover the parts that must not
depend on the model: refusal, validation, storage, and the tiers.
"""
from __future__ import annotations

import json
from pathlib import Path

import pytest

from app.services.media_trust import (
    MediaListStore,
    MediaPolicy,
    believe_domains,
    is_refused_host,
    looks_like_news_domain,
    normalize_host,
    order_by_trust,
    TIER_FALLBACK,
    TIER_GLOBAL,
    TIER_NATIONAL,
    TIER_PRIMARY,
)


# --- refusal: the rule that does not depend on local knowledge ----

@pytest.mark.parametrize(
    "host",
    [
        "reddit.com",
        "old.reddit.com",
        "x.com",
        "twitter.com",
        "linkedin.com",
        "facebook.com",
        "youtube.com",
        "wikipedia.org",
        "medium.com",
        "glassdoor.com",
        "indeed.com",
        "stocktwits.com",
        "zippia.com",
    ],
)
def test_rumour_and_platform_hosts_are_refused(host):
    assert is_refused_host(host) is True


@pytest.mark.parametrize(
    "host",
    ["reuters.com", "nikkei.com", "handelsblatt.com", "sec.gov", "jiji.com"],
)
def test_real_publications_are_not_refused(host):
    assert is_refused_host(host) is False


def test_refusal_matches_subdomains_but_not_similar_names():
    assert is_refused_host("https://old.reddit.com/r/x") is True
    # A publication whose name merely contains a refused string is fine.
    assert is_refused_host("redditsomething-news.com") is False


# --- validation: a generated list is believed only after checking ----

def test_a_plausible_publication_is_accepted():
    assert looks_like_news_domain("nikkei.com") is True
    assert looks_like_news_domain("handelsblatt.com") is True


def test_a_local_edition_of_an_international_brand_is_rejected():
    # "bloomberg.co.jp" would spend a national slot on a title the reader already
    # gets from the global tier.
    assert looks_like_news_domain("bloomberg.co.jp") is False
    assert looks_like_news_domain("economist.jp") is False


def test_platforms_and_job_boards_are_rejected():
    assert looks_like_news_domain("linkedin.com") is False
    assert looks_like_news_domain("indeed.com") is False


def test_nonsense_strings_are_rejected():
    for value in ("", "  ", "news", "https://x.com/a", "not a domain", "www.blog"):
        assert looks_like_news_domain(value) is False, value


def test_believe_domains_keeps_order_and_drops_junk():
    kept = believe_domains(
        ["nikkei.com", "reddit.com", "jiji.com", "bloomberg.co.jp", "nikkei.com"]
    )

    assert kept == ("nikkei.com", "jiji.com")


# --- storage --------------------------------------------------------

def test_a_list_is_stored_and_reused(tmp_path):
    store = MediaListStore(path=tmp_path / "media.json")
    store.put("JP", {"country": "Japan", "domains": ["nikkei.com"], "confidence": "high"})

    entry = store.get("JP")

    assert entry["domains"] == ["nikkei.com"]
    # Persisted to disk, so a restart does not pay for generation again.
    payload = json.loads((tmp_path / "media.json").read_text(encoding="utf-8"))
    assert "JP" in payload


def test_the_store_survives_a_reload(tmp_path):
    path = tmp_path / "media.json"
    first = MediaListStore(path=path)
    first.put("JP", {"domains": ["nikkei.com"]})

    second = MediaListStore(path=path)

    assert second.get("JP")["domains"] == ["nikkei.com"]


def test_an_unreadable_store_is_ignored_not_fatal(tmp_path):
    path = tmp_path / "media.json"
    path.write_text("{not json", encoding="utf-8")
    store = MediaListStore(path=path)

    assert store.get("JP") is None


def test_jurisdiction_keys_are_case_insensitive(tmp_path):
    store = MediaListStore(path=tmp_path / "media.json")
    store.put("jp", {"domains": ["nikkei.com"]})

    assert store.get("JP")["domains"] == ["nikkei.com"]


# --- the tiers ------------------------------------------------------

def test_primary_beats_national_and_national_beats_global():
    policy = MediaPolicy(
        jurisdiction="JP", national=("nikkei.com",), jurisdiction_known=True
    )

    assert policy.tier_of("sec.gov") == TIER_PRIMARY
    assert policy.tier_of("nikkei.com") == TIER_NATIONAL
    assert policy.tier_of("reuters.com") == TIER_GLOBAL
    assert policy.rank("nikkei.com") < policy.rank("reuters.com")
    assert policy.rank("sec.gov") < policy.rank("nikkei.com")


def test_an_unknown_publication_is_read_last_but_read():
    policy = MediaPolicy(jurisdiction="JP", national=("nikkei.com",), jurisdiction_known=True)

    assert policy.tier_of("someblog.example.com") == TIER_FALLBACK
    assert policy.rank("someblog.example.com") > policy.rank("reuters.com")


def test_without_a_known_country_national_press_cannot_be_ranked():
    # No list means no guess: ranking a wrong country's press first would narrow
    # every brief on that company without anyone noticing.
    policy = MediaPolicy(jurisdiction=None, jurisdiction_known=False)

    assert policy.tier_of("nikkei.com") == TIER_FALLBACK
    assert "could not be ranked" in policy.description


def test_refused_hosts_sort_last():
    policy = MediaPolicy(jurisdiction="JP", national=("nikkei.com",), jurisdiction_known=True)

    assert policy.rank("reddit.com") > policy.rank("someblog.example.com")


def test_ordering_drops_refused_and_ranks_the_rest():
    policy = MediaPolicy(jurisdiction="JP", national=("nikkei.com",), jurisdiction_known=True)
    results = [
        {"url": "https://reddit.com/r/x"},
        {"url": "https://reuters.com/a"},
        {"url": "https://nikkei.com/b"},
        {"url": "https://sec.gov/c"},
    ]

    ordered = order_by_trust(results, policy)

    assert [item["url"] for item in ordered] == [
        "https://sec.gov/c",
        "https://nikkei.com/b",
        "https://reuters.com/a",
    ]


def test_normalize_host_strips_scheme_port_and_www():
    assert normalize_host("https://www.nikkei.com/a") == "nikkei.com"
    assert normalize_host("http://nikkei.com:8080/b") == "nikkei.com"
    assert normalize_host("nikkei.com") == "nikkei.com"
